#!/usr/bin/env node
// Add FlightStrips to an existing GSX airport handler script, or update it.
//
//     node gsx-client/tools/embed.js path/to/EGKK-MyScenery_handler.py
//     node gsx-client/tools/embed.js path/to/X_handler.py --scenery Simnord-Sonnich
//
// Copies everything from API_BASE to the end of EKCH-Simnord-Sonnich_handler.py
// between two marker lines at the end of the target script. Run it again to
// update: the block between the markers is replaced, and the API_BASE and
// SCENERY it held are kept unless --scenery or --api-base says otherwise.
//
// The block's settings and constants are renamed FS_<NAME> (FS_API_BASE,
// FS_SCENERY...). The host script and the block share one module namespace,
// so without the prefix the block's API_BASE would replace a host's own.
//
// The target script keeps its own GSX callbacks. The FlightStrips block
// captures any it finds before defining its own and calls them first, so the
// profile's own behaviour (operators, vehicles) carries on unchanged.

const fs = require("fs");
const path = require("path");

const BEGIN = "# >>> FlightStrips - generated by gsx-client/tools/embed.js, do not edit by hand >>>";
const END = "# <<< FlightStrips <<<";
const SOURCE = path.join(__dirname, "..", "EKCH-Simnord-Sonnich_handler.py");
const PREFIX = "FS_";
const DEFAULT_API_BASE = "https://api.flightstrips.dk";

function fail(message) {
  console.error(message);
  process.exit(1);
}

const args = process.argv.slice(2);
const target = args.find((a) => !a.startsWith("--"));
if (!target) fail("usage: embed.js <profile_handler.py> [--scenery KEY] [--api-base URL]");
const option = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};

const source = fs.readFileSync(SOURCE, "utf8").replace(/\r\n/g, "\n");
const start = source.search(/^API_BASE = /m);
if (start < 0) fail(`no API_BASE line in ${SOURCE}`);
let block = source.slice(start).replace(/\s+$/, "\n");

// Namespace every top-level constant the block defines, and each use of it.
const constants = [...new Set([...block.matchAll(/^([A-Z][A-Z0-9_]*)\s*=/gm)].map((m) => m[1]))];
for (const name of constants) {
  block = block.replace(new RegExp(`\\b${name}\\b`, "g"), PREFIX + name);
}

const original = fs.readFileSync(target, "utf8");
const eol = original.includes("\r\n") ? "\r\n" : "\n";
let text = original.replace(/\r\n/g, "\n");

// Keep the settings an earlier run left, unless told otherwise. Either quote
// style and a trailing comment are fine; a setting line that cannot be read
// stops the run rather than quietly resetting it. A block embedded before the
// FS_ prefix holds the bare name.
const begin = text.indexOf(BEGIN);
const inside = begin >= 0 ? text.slice(begin, text.indexOf(END, begin) >>> 0) : "";
const setting = (name, flag, fallback) => {
  const given = option(flag);
  if (given !== undefined) return given;
  const line = inside.match(new RegExp(`^(?:${PREFIX})?${name}\\s*=.*$`, "m"));
  if (!line) return fallback;
  const kept = line[0].match(/=\s*(?:"([^"\\]*)"|'([^'\\]*)')\s*(?:#.*)?$/);
  if (!kept) fail(`cannot read ${name} in ${target}: ${line[0].trim()}\nfix that line, or pass ${flag}`);
  return kept[1] !== undefined ? kept[1] : kept[2];
};
const apiBase = setting("API_BASE", "--api-base", DEFAULT_API_BASE);
const scenery = setting("SCENERY", "--scenery", "");
block = block
  .replace(new RegExp(`^${PREFIX}API_BASE = .*$`, "m"), `${PREFIX}API_BASE = ${JSON.stringify(apiBase)}`)
  .replace(new RegExp(`^${PREFIX}SCENERY = .*$`, "m"), `${PREFIX}SCENERY = ${JSON.stringify(scenery)}`);

const header = [
  BEGIN,
  "# FlightStrips stand and pushback assignment for VATSIM. Source and docs:",
  "# https://github.com/flightstrips/FlightStrips/tree/main/gsx-client",
  `# Set ${PREFIX}API_BASE or ${PREFIX}SCENERY below; anything else, change the source and re-run.`,
  "",
].join("\n");
const wrapped = `${header}${block}${END}\n`;

if (begin >= 0) {
  const end = text.indexOf(END, begin);
  if (end < 0) fail(`found the start marker but not "${END}" in ${target}`);
  text = text.slice(0, begin) + wrapped + text.slice(end + END.length).replace(/^\n/, "");
} else {
  text = text.replace(/\s+$/, "\n") + "\n\n" + wrapped;
}

// Anything outside the block that the block would silently replace: its
// functions and state (_stand...) and its namespaced constants (FS_...).
const outside = text.slice(0, text.indexOf(BEGIN)) + text.slice(text.indexOf(END) + END.length);
const clashes = [...outside.matchAll(/^(?:def\s+(\w+)|(\w+)\s*=)/gm)]
  .map((m) => m[1] || m[2])
  .filter((name) => /^(?:_stand\w*|FS_[A-Z0-9_]+)$/.test(name));
if (clashes.length) {
  console.warn(`warning: ${target} defines names the FlightStrips block also uses: ${[...new Set(clashes)].join(", ")}`);
}

fs.writeFileSync(target, eol === "\n" ? text : text.replace(/\n/g, eol));
console.log(`${begin >= 0 ? "updated" : "added"} FlightStrips in ${target}`);
console.log(`  ${PREFIX}API_BASE = ${JSON.stringify(apiBase)}`);
console.log(`  ${PREFIX}SCENERY = ${JSON.stringify(scenery)}`);
