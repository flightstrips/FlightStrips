const assert = require("node:assert/strict");
const { spawnSync } = require("node:child_process");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { test } = require("node:test");

function fixture(t, name, content) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "flightstrips-gsx-"));
  t.after(() => fs.rmSync(dir, { recursive: true }));
  const file = path.join(dir, name);
  fs.writeFileSync(file, content);
  return file;
}

function run(script, ...args) {
  const result = spawnSync(process.execPath, [path.join(__dirname, script), ...args], { encoding: "utf8" });
  if (result.error) throw result.error;
  return result;
}

test("embed preserves escaped settings and literal replacement characters", (t) => {
  const profile = fixture(t, "EKCH-Test_handler.py", 'API_BASE = "https://profile.example"\n');
  const scenery = 'North "Cargo" \\ $& $$ # <<< FlightStrips <<<';
  const apiBase = "https://mock.example/$&?dollar=$$";
  const first = run("embed.js", profile, "--scenery", scenery, "--api-base", apiBase);
  assert.equal(first.status, 0, first.stderr);
  const embedded = fs.readFileSync(profile, "utf8");
  assert.ok(embedded.includes("\nFS_SCENERY = " + JSON.stringify(scenery) + "\n"));
  assert.ok(embedded.includes("\nFS_API_BASE = " + JSON.stringify(apiBase) + "\n"));
  assert.ok(embedded.startsWith('API_BASE = "https://profile.example"\n'));

  const update = run("embed.js", profile);
  assert.equal(update.status, 0, update.stderr);
  assert.equal(fs.readFileSync(profile, "utf8"), embedded);
});

test("embed retains legacy Python literals and rejects computed settings without modifying the file", (t) => {
  const begin = "# >>> FlightStrips - generated by gsx-client/tools/embed.js, do not edit by hand >>>";
  const end = "# <<< FlightStrips <<<";
  const legacy = "'North \\'Cargo\\' \\\\ $&'";
  const profile = fixture(t, "EKCH-Legacy_handler.py", [begin, "SCENERY = " + legacy + " # note", end, ""].join("\n"));
  const update = run("embed.js", profile);
  assert.equal(update.status, 0, update.stderr);
  assert.ok(fs.readFileSync(profile, "utf8").includes("\nFS_SCENERY = " + legacy + "\n"));

  const computed = [begin, 'FS_API_BASE = get_url() # old = "https://old.example"', end, ""].join("\n");
  fs.writeFileSync(profile, computed);
  const failed = run("embed.js", profile);
  assert.equal(failed.status, 1);
  assert.match(failed.stderr, /cannot read API_BASE/);
  assert.equal(fs.readFileSync(profile, "utf8"), computed);
});

test("audit counts extra routes across key order, quote style, and missing positions", (t) => {
  const extras = [
    "{'pos': (55.627587, 12.632347, 90), 'label': 'Z1 reversed'}",
    '{"label": "Z1 spaced", "approach": [(55.6, 12.6, 90)], "pos": (55.627587, 12.632347, 90)}',
    '{"label": "Z1 Cargo \\"West\\" {A}: gate", "meta": {"pos": (1, 2)}, "pos": [55.627587, 12.632347, 90]}',
    "{'label': 'Z1 computed', 'pos': None}",
  ];
  const profile = fixture(t, "EKCH-Test.ini", "[Gate Test]\npushback=0\npushbackaddpos=[" + extras.join(", ") + "]\n");
  const result = run("audit.js", profile);
  assert.equal(result.status, 1, result.stderr);
  assert.match(result.stdout, /MISLABEL +Z1 reversed +ends at Z2/);
  assert.match(result.stdout, /MISLABEL +Z1 spaced +ends at Z2/);
  assert.match(result.stdout, /MISLABEL +Z1 Cargo "West" \{A\}: gate +ends at Z2/);
  assert.match(result.stdout, /NO POS +Z1 computed/);
  assert.match(result.stdout, /4 routes checked .* 4 flagged/);
});

